void locale_set(lang_t lang)
{
    if (lang < LANG_COUNT) s_lang = lang;
}

lang_t locale_get(void)
{
    return s_lang;
}

const char *t(locale_key_t key)
{
    if (key >= L_KEY_COUNT) return "";
    const char *s = s_tables[s_lang][key];
    return s ? s : (s_en[key] ? s_en[key] : "");
}
